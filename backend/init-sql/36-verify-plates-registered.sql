-- ============================================================================
-- 36. 回归专用车牌进车辆备案（车型/载重能补齐，不再让「本次运单车型为空」变红）
--
-- 背景（2026-10-10）：
--   装车口「同一趟车继续装」的并入逻辑上线后，回归脚本里的正向用例不能再借用
--   演示车牌 京A·12345 —— 它名下常年挂着界面演示建出的待发车运单，会被并进去。
--   所以各脚本改用**测试专用车牌**（照 verify-depart 早就定下的约定）：
--     京A·T0001 刷卡发车 / 京A·T0002 站点到达 / 京A·T0003 装车口分车 /
--     京A·T0004 多站车次 / 京A·T0005 温度断档
--   而「车型」的口径是「计划填了用计划的，没填则用『车牌 → 车辆备案』带出来」，
--   备案里没有这几张测试车牌，车型就补不出来 —— 回归里那条
--   「本次运单车型都齐全」会红，且红得**没错**（是数据缺，不是代码错）。
--
-- 口径：**备案不是准入门槛**（新车、外调车天天有，查不到照样放行，只影响车型展示
--   与载重判断），但「常跑的测试车」本来就该备案 —— 补上它才是真实的样子。
--
-- 本脚本只补数据，不改表结构；INSERT IGNORE 保证重复执行安全。
-- ============================================================================

INSERT IGNORE INTO db_distribution.vehicle
    (vehicle_no, vehicle_type, load_capacity_kg, owner_name, status, remark)
VALUES
    ('京A·T0001', '冷藏车', 5000.00, '自有车队', 1, '回归专用车牌（刷卡发车 DEPART）'),
    ('京A·T0002', '冷藏车', 5000.00, '自有车队', 1, '回归专用车牌（站点级到达 ARRIVE）'),
    ('京A·T0003', '冷藏车', 5000.00, '自有车队', 1, '回归专用车牌（装车口分车 LOAD）'),
    ('京A·T0004', '冷藏车', 5000.00, '自有车队', 1, '回归专用车牌（一车多站 LOAD）'),
    ('京A·T0005', '冷藏车', 5000.00, '自有车队', 1, '回归专用车牌（冷链温度 LOAD）');

-- 核对：五张测试车牌都已备案，且车型非空
SELECT vehicle_no, vehicle_type, load_capacity_kg, status
FROM db_distribution.vehicle
WHERE vehicle_no LIKE '京A·T%'
ORDER BY vehicle_no;

-- 核对：备案里不该有重复车牌（唯一键是最终权威，这里只是显式确认）
SELECT COUNT(*) AS dup_plates
FROM (SELECT vehicle_no FROM db_distribution.vehicle GROUP BY vehicle_no HAVING COUNT(*) > 1) x;
