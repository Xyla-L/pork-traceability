-- ============================================================================
-- 车载终端合并：发车确认与到站刷卡确认由同一台设备承担
--
-- 背景（2026-10-11）：到站确认最初按「门店收货区的固定设备」设计（32 号迁移建了
--   ARRIVE-001「门店收货区到达确认终端」），改成「司机在车载终端刷卡」之后，它和发车确认
--   （DEPART）就是**同一台车上的同一台设备**：同一个驾驶室、同一个读卡头、同一把密钥。
--   系统侧由 IngestChannel.deviceGroup() 把两者归为「同一台终端能上报的两个通道」
--   （resolveChannel 允许同组互报），所以台账里不该再摆第二台设备 —— 现场也装不了两台，
--   一个驾驶室只有一块屏、一个读卡头。
--
-- 本次只改台账「这台设备是什么、装在哪、能报什么」，**不动设备码**：
--   · ARRIVE-001     → 升格为「车载终端（发车 / 到站刷卡）」，设备码保留（历史暂存行仍指向它）
--   · DEPART-001/003 → 名称去掉「发车」二字，改为「车载终端 京A·xxxxx」——
--     它们本来就同时承担到站刷卡，只是名字一直只提了发车
--
-- 为什么不改设备码：device_no 是设备侧的出厂/现场标识，不该带业务语义。改码要牵动 4 个
--   回归脚本与前端，换不来任何业务收益，反而让「同一台车的同一个终端」在回归里看起来
--   像换了一台设备。
--
-- 幂等：全部用 UPDATE（重复执行结果一致；location 用 SUBSTRING_INDEX 取前缀也稳定）。
-- 执行：docker cp 进 mysql 容器后
--       `mysql -uroot -p"$MYSQL_ROOT_PASSWORD" --default-character-set=utf8mb4 < 本文件`
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1) 到站终端升格为「车载终端」（一台设备承担两个通道）
-- ---------------------------------------------------------------------------
UPDATE db_ingest.ingest_device
SET device_name = '车载终端（发车 / 到站刷卡）',
    location    = '驾驶室（司机上车刷卡 / 到站刷卡）',
    remark      = '车载终端：同一台设备承担两个通道 —— 发车确认（司机上车刷卡，把责任落到具体人）与到站刷卡确认（每刷一次推进一站）。两通道同组，见 IngestChannel.deviceGroup()。本行不绑车牌：它是演示/回归用的通用终端，车牌以报文里的 vehicleNo 为准。'
WHERE device_no = 'ARRIVE-001';


-- ---------------------------------------------------------------------------
-- 2) 发车终端改称「车载终端」（它们同样承担到站刷卡，名字一直只提了发车）
-- ---------------------------------------------------------------------------
UPDATE db_ingest.ingest_device
SET device_name = CONCAT('车载终端 ', vehicle_no),
    location    = CONCAT(SUBSTRING_INDEX(location, '驾驶室', 1), '驾驶室（司机上车刷卡 / 到站刷卡）'),
    remark      = '车载终端：同一台设备承担两个通道 —— 发车确认（司机上车刷卡）与到站刷卡确认（每刷一次推进一站）。'
WHERE device_no IN ('DEPART-001', 'DEPART-003');


-- ---------------------------------------------------------------------------
-- 3) 核验
-- ---------------------------------------------------------------------------
SELECT '车载终端台账' AS item,
       CONCAT(device_no, ' | ', device_name, ' | ', IFNULL(vehicle_no, '（不绑车牌）'),
              ' | ', IFNULL(location, '')) AS v
FROM db_ingest.ingest_device
WHERE device_no IN ('ARRIVE-001', 'DEPART-001', 'DEPART-003');

SELECT '全库设备台数（合并不增删行，仍应是 23）' AS item,
       CAST(COUNT(*) AS CHAR) AS v
FROM db_ingest.ingest_device;
